//! The glyph table. Each glyph is a width and a spec string of strokes separated by `|`; a stroke
//! is a list of `x,y` points (y up; baseline 0, x-height 4, cap height 6, descenders to -2).
//! Prefix `~` smooths an open stroke through its points (corner cutting); prefix `o` makes a
//! smooth closed loop. Plain strokes keep their corners.

use std::collections::HashMap;
use std::sync::OnceLock;

use kurbo::Point;

pub struct Stroke {
    pub points: Vec<Point>,
    pub closed: bool,
}

pub struct Glyph {
    pub width: f64,
    pub strokes: Vec<Stroke>,
}

/// Looks a character up; unknown characters give a box and `false`.
pub fn lookup(c: char) -> (&'static Glyph, bool) {
    let table = table();
    match table.get(&c) {
        Some(g) => (g, true),
        None => (&table[&'\u{0}'], c == '\r' || c == '\u{0}'),
    }
}

fn table() -> &'static HashMap<char, Glyph> {
    static TABLE: OnceLock<HashMap<char, Glyph>> = OnceLock::new();
    TABLE.get_or_init(|| {
        let mut m: HashMap<char, Glyph> = SPECS.iter().map(|(c, w, spec)| (*c, build(*w, spec))).collect();
        // The fallback box, stored under NUL.
        m.insert('\u{0}', build(4.0, "0,0 4,0 4,6 0,6 0,0"));
        m
    })
}

fn build(width: f64, spec: &str) -> Glyph {
    let strokes = spec.split('|').filter_map(parse_stroke).collect();
    Glyph { width, strokes }
}

fn parse_stroke(s: &str) -> Option<Stroke> {
    let s = s.trim();
    let (mode, rest) = match s.chars().next()? {
        '~' => (Mode::Smooth, &s[1..]),
        'o' => (Mode::Loop, &s[1..]),
        _ => (Mode::Sharp, s),
    };
    let points: Vec<Point> = rest
        .split_whitespace()
        .filter_map(|pair| {
            let (x, y) = pair.split_once(',')?;
            Some(Point::new(x.parse().ok()?, y.parse().ok()?))
        })
        .collect();
    if points.len() < 2 {
        return None;
    }
    Some(match mode {
        Mode::Sharp => Stroke { points, closed: false },
        Mode::Smooth => Stroke { points: chaikin(&points, false, 3), closed: false },
        Mode::Loop => Stroke { points: chaikin(&points, true, 3), closed: true },
    })
}

enum Mode {
    Sharp,
    Smooth,
    Loop,
}

/// Chaikin corner cutting; open strokes keep their end points.
fn chaikin(points: &[Point], closed: bool, rounds: usize) -> Vec<Point> {
    let mut pts = points.to_vec();
    for _ in 0..rounds {
        let n = pts.len();
        let mut out = Vec::with_capacity(n * 2);
        let segments = if closed { n } else { n - 1 };
        if !closed {
            out.push(pts[0]);
        }
        for i in 0..segments {
            let (a, b) = (pts[i], pts[(i + 1) % n]);
            let q = Point::new(0.75 * a.x + 0.25 * b.x, 0.75 * a.y + 0.25 * b.y);
            let r = Point::new(0.25 * a.x + 0.75 * b.x, 0.25 * a.y + 0.75 * b.y);
            // Keep the original end points of an open stroke exactly.
            if !closed && i == 0 {
                out.push(r);
            } else if !closed && i == segments - 1 {
                out.push(q);
            } else {
                out.push(q);
                out.push(r);
            }
        }
        if !closed {
            out.push(pts[n - 1]);
        }
        pts = out;
    }
    pts
}

